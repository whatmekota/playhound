"""
Generates the 2.0 logo set from the current public/logos/*.svg colourings.

Same drawing as 1.x (nose, side grin, teeth band with the fang), restyled for 2.0:
a gloss highlight, the snout shade (the lit snout is a band; shade above it and off
the front of the muzzle, as on the avatar) and a thin inner rim. The in-app marks
stay square without drips (they show at 18 px); the desktop icon is the same
square mark (drips would turn to noise at taskbar sizes). The splash uses a sticker
version of each colouring: a pale halo, a rim, and goo dripping off the tile.

    python brand/v2/make-icons.py   -> brand/v2/icons/*.svg, *-sticker.svg, favicon.svg
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / 'source-1x'  # the 1.x colourings, kept here since public/logos now holds the output
OUT = Path(__file__).resolve().parent / 'icons'
OUT.mkdir(exist_ok=True)

IDS = ['sly-grin', 'night', 'noir', 'crimson', 'violet', 'orange', 'lime']

NOSE = 'M47 6 L60 8.5 L53.5 15.5 Z'
MOUTH = 'M7 19 C14 31 27 43 43.5 48 L47 48 L54.5 22 C45 21.6 36.5 23.5 28.4 26.2 C20.4 25.6 13 22.8 7 19Z'
TONGUE = 'M15.5 30.6 C25.5 28.6 37 32.6 44.6 41.6 L46 48.2 C35.6 47 25.4 40.6 15.5 30.6Z'
TOOTH = 'M29.6 42.2 L33.4 35.4 L35 45.4 Z'
TEETH = 'M26.4 25.6 C35 22.6 45 20.2 54.4 19 L58.4 21.4 C57.2 23 56.2 24.8 55.4 26.6 C54.6 30.6 54.2 34 54 37.6 C52.2 34 51 30.2 50.4 26.2 C43.6 27 36.6 28.6 30.4 31 Z'
FANG = 'M45.8 48.4 C49.2 46 51.4 42.8 52.4 39 C53.4 43.4 52.6 46.6 51 48.8 Z'
OUT_TONGUE = 'M17 31.6 C25 30 32.6 32.4 37.8 37.6 C40.4 41.6 41.4 46.6 40.4 52.6 C39.4 58.4 34.6 61.6 30.2 59.8 C26.4 58.2 26.2 53.6 27.4 49.6 C28.2 46.6 28 43.4 26 40.8 C23.6 37.6 20.4 34.8 17 31.6Z'
OUT_LINE = 'M32.8 41 C34.6 45 34.8 50 33.4 55.6'
# The snout shade (avatar P4): everything but a band across the tile, cut along the snout's front.
BAND = 'M-30 -30 H90 V90 H-30 Z M-20 -10.5 L1 -7.4 C26 -3.6 44 1 57 4.4 C59.6 5.2 61 6.6 61.8 9.4 C60.8 16 59.8 24 59 30 C58 37 57.2 42 56.8 46 C56.2 51.4 53.6 55.4 47.6 57.2 C36 59 20 59.6 -20 61 Z'
TILE = 'M17 2 H47 C55.3 2 62 8.7 62 17 V47 C62 55.3 55.3 62 47 62 H17 C8.7 62 2 55.3 2 47 V17 C2 8.7 8.7 2 17 2Z'
DRIPS = [(14, 7), (26, 13), (40, 5)]


def fills_by_path(svg):
    """Map each known shape's d= to its fill, from an existing logo file."""
    out = {}
    for m in re.finditer(r'<path d="([^"]+)"([^>]*)/?>', svg):
        d, rest = m.group(1), m.group(2)
        f = re.search(r'fill="([^"]+)"', rest)
        o = re.search(r'opacity="([^"]+)"', rest)
        s = re.search(r'stroke="([^"]+)"', rest)
        out[d] = (f.group(1) if f else None, o.group(1) if o else None, s.group(1) if s else None)
    return out


def palette(id_):
    a = (SRC / f'{id_}.svg').read_text(encoding='utf-8')
    t = (SRC / f'{id_}-tongue.svg').read_text(encoding='utf-8')
    stops = re.findall(r'stop-color="([^"]+)"', a)
    tile = re.search(r'<rect x="2" y="2" width="60" height="60" rx="15" fill="([^"]+)"', a).group(1)
    fa, ft = fills_by_path(a), fills_by_path(t)
    shade = next(((f, o) for d, (f, o, _) in fa.items() if d.startswith('M64 13')), ('#000', '.5'))
    return {
        'stops': stops if tile.startswith('url(') else None,
        'tile': None if tile.startswith('url(') else tile,
        'nose': fa[NOSE][0], 'mouth': fa[MOUTH][0], 'tongue': fa[TONGUE][0],
        'shade': shade[0], 'shadeOp': float(shade[1] or 1),
        'outTongue': ft[OUT_TONGUE][0], 'outLine': ft[OUT_LINE][2],
    }


def grad(p, gid='t'):
    if p['stops']:
        s = p['stops']
        return f'<linearGradient id="{gid}" x1="6" y1="4" x2="58" y2="62" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{s[0]}"/><stop offset=".45" stop-color="{s[1]}"/><stop offset="1" stop-color="{s[2]}"/></linearGradient>', f'url(#{gid})'
    return '', p['tile']


def face(p, tongue):
    parts = [f'<path d="{NOSE}" fill="{p["nose"]}"/>', f'<path d="{MOUTH}" fill="{p["mouth"]}"/>']
    if not tongue:
        parts += [f'<path d="{TONGUE}" fill="{p["tongue"]}"/>', f'<path d="{TOOTH}" fill="#fff"/>']
    parts.append(f'<path d="{TEETH}" fill="#fff"/>')
    if tongue:
        parts.append(f'<g transform="translate(3 1.6) rotate(-4 30 40)"><path d="{OUT_TONGUE}" fill="{p["outTongue"]}"/><path d="{OUT_LINE}" fill="none" stroke="{p["outLine"]}" stroke-width="1.6" stroke-linecap="round"/></g>')
    parts.append(f'<path d="{FANG}" fill="#fff"/>')
    return '\n    '.join(parts)


def mark(id_, tongue):
    """The in-app mark: square, no drips."""
    p = palette(id_)
    g, fill = grad(p)
    shade_op = min(1, p['shadeOp'] * 0.9 + 0.05)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- playhound 2.0 · {id_}{", tongue out" if tongue else ""} (generated by brand/v2/make-icons.py) -->
  <defs>{g}<clipPath id="c"><path d="{TILE}"/></clipPath></defs>
  <path d="{TILE}" fill="{fill}"/>
  <g clip-path="url(#c)">
    <path d="{BAND}" fill-rule="evenodd" fill="{p["shade"]}" opacity="{shade_op:.2f}"/>
    <path d="M6.6 14.6 C7 10 10 7 15.6 6.6" fill="none" stroke="#fff" stroke-width="2.6" stroke-linecap="round" opacity=".5"/>
    <path d="{TILE}" fill="none" stroke="{p["shade"]}" stroke-width="2.4" opacity=".55"/>
  </g>
    {face(p, tongue)}
</svg>
'''


def mix(a, b, t):
    a, b = [int(a[i:i + 2], 16) for i in (1, 3, 5)], [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return '#' + ''.join(f'{round(x + (y - x) * t):02x}' for x, y in zip(a, b))


def sticker(id_, tongue=False):
    """The splash mark: the mark as a sticker with a halo, a rim, and goo off the bottom of the tile."""
    p = palette(id_)
    halo = mix(p['stops'][0], '#ffffff', 0.6) if p['stops'] and id_ != 'noir' else ('#3a0c45' if id_ == 'night' else '#d4d4d8')
    rim = '#e879f9' if id_ == 'night' else p['shade']  # night: a neon rim, as on the design sheet
    g, fill = grad(p)
    drips = ''.join(f'<path d="M{x - 2.6} 60 C{x - 2.6} {62 + L * 0.6} {x - 2} {62 + L} {x} {62 + L} C{x + 2} {62 + L} {x + 2.6} {62 + L * 0.6} {x + 2.6} 60Z"/>' for x, L in DRIPS)
    shape = f'<path d="{TILE}"/>{drips}'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -4 80 80">
  <!-- playhound 2.0 · {id_} sticker{", tongue out" if tongue else ""}, for the splash (generated by brand/v2/make-icons.py) -->
  <defs>{g}<clipPath id="c"><path d="{TILE}"/></clipPath></defs>
  <g fill="{halo}" stroke="{halo}" stroke-width="6.2" stroke-linejoin="round">{shape}</g>
  <g fill="{rim}" stroke="{rim}" stroke-width="3.4" stroke-linejoin="round">{shape}</g>
  <g fill="{fill}">{shape}</g>
  <g clip-path="url(#c)">
    <path d="{BAND}" fill-rule="evenodd" fill="{p["shade"]}" opacity="{min(1, p["shadeOp"] * 0.9 + 0.05):.2f}"/>
    <path d="M6.6 14.6 C7 10 10 7 15.6 6.6" fill="none" stroke="#fff" stroke-width="2.6" stroke-linecap="round" opacity=".55"/>
  </g>
    {face(p, tongue)}
</svg>
'''


for i in IDS:
    (OUT / f'{i}.svg').write_text(mark(i, False), encoding='utf-8')
    (OUT / f'{i}-tongue.svg').write_text(mark(i, True), encoding='utf-8')
    (OUT / f'{i}-sticker.svg').write_text(sticker(i, False), encoding='utf-8')
    (OUT / f'{i}-tongue-sticker.svg').write_text(sticker(i, True), encoding='utf-8')
# The app icon (desktop/taskbar/installer, rendered from public/favicon.svg): the plain square mark.
(OUT / 'favicon.svg').write_text(mark('sly-grin', False), encoding='utf-8')
print('wrote', len(list(OUT.glob('*.svg'))), 'files to', OUT)
